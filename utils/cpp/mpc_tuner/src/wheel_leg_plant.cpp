using Coefficients = std::array<double, 10>;

double polynomial(const Coefficients& c, const double x, const double y) {
    return c[0] + c[1] * x + c[2] * y + c[3] * x * x + c[4] * x * y + c[5] * y * y
        + c[6] * x * x * x + c[7] * x * x * y + c[8] * x * y * y + c[9] * y * y * y;
}

double wrap_pi(const double angle) {
    return std::atan2(std::sin(angle), std::cos(angle));
}

