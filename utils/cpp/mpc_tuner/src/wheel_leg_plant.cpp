WheelLegPlant::WheelLegPlant() {
    update_model_cache();
}

void WheelLegPlant::reset(const Eigen::Vector3d& pose, const uint64_t seed) {
    state_.setZero();
    pose_ = pose;
    state_(2) = pose.z();
    velocity_target_ = omega_target_ = velocity_applied_ = omega_applied_ = 0.0;
    theta_target_ = pose.z();
    s_reference_ = 0.0;
    rng_.seed(seed);
}

std::pair<double, double> WheelLegPlant::clamp_command(double velocity, double omega) {
    velocity = std::clamp(velocity, -2.8, 2.8);
    omega = std::clamp(omega, -7.2, 7.2);
    const double product = std::abs(velocity * omega);
    if (product > 3.5) {
        const double scale = std::sqrt(3.5 / product);
        velocity *= scale;
        omega *= scale;
    }
    return {velocity, omega};
}

double WheelLegPlant::rate_limit(const double current, const double target, const double max_rate) {
    return current + std::clamp(target - current, -max_rate * DT, max_rate * DT);
}

