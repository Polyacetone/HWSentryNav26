void WheelLegPlant::lqr_substep() {
    velocity_applied_ = rate_limit(velocity_applied_, velocity_target_, 2.5);
    const double previous_omega_applied = omega_applied_;
    omega_applied_ = rate_limit(omega_applied_, omega_target_, 12.0);
    std::tie(velocity_applied_, omega_applied_) = clamp_command(velocity_applied_, omega_applied_);
    theta_target_ = wrap_pi(theta_target_ + 0.5 * (previous_omega_applied + omega_applied_) * DT);
    s_reference_ = state_(0) + velocity_applied_ * DT;

    State reference = State::Zero();
    reference(0) = s_reference_;
    reference(1) = velocity_applied_;
    reference(2) = theta_target_;
    reference(3) = omega_applied_;
    State error = state_ - reference;
    error(2) = wrap_pi(state_(2) - theta_target_);

    Input disturbance;
    for (int i = 0; i < INPUT_DIM; ++i) disturbance(i) = 0.04 * standard_normal_(rng_);
    Input input = -k_ * error + u_d_ + disturbance;
    input(0) = std::clamp(input(0), -20.0, 20.0);
    input(1) = std::clamp(input(1), -20.0, 20.0);
    input(2) = std::clamp(input(2), -30.0, 30.0);
    input(3) = std::clamp(input(3), -30.0, 30.0);

    state_ += (a_ * state_ + b_ * input) * DT;
    const double velocity = state_(1);
    pose_.x() += velocity * std::cos(pose_.z()) * DT;
    pose_.y() += velocity * std::sin(pose_.z()) * DT;
    pose_.z() = wrap_pi(state_(2));
}

std::vector<PlantSample> WheelLegPlant::step(const Eigen::Vector2d& command, const double duration) {
    std::tie(velocity_target_, omega_target_) = clamp_command(command.x(), command.y());
    const int substeps = std::max(1, static_cast<int>(std::lround(duration / DT)));
    std::vector<PlantSample> samples;
    samples.reserve(static_cast<size_t>(substeps));
    for (int i = 0; i < substeps; ++i) {
        lqr_substep();
        samples.push_back(sample());
    }
    return samples;
}

PlantSample WheelLegPlant::sample() const {
    return {
        .pose = pose_,
        .chassis = {
            .velocity = state_(1),
            .omega = state_(3),
            .leg_h = 0.5 * (leg_left_ + leg_right_),
            .leg_psi = 0.5 * (state_(4) + state_(6)),
        },
    };
}

